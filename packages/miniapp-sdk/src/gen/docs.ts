// `tb-gen docs`: generated reference docs `<product>.md` from the whole manifest (MANIFEST §14). Names and labels only:
// no key values exist in the manifest, and none are printed.
import { dynamicToolNames, mcpToolName, withStandardOps } from "@opt2-tealbrick/manifest";
import type { Manifest } from "@opt2-tealbrick/spec/manifest";
import { cell, conditionText, type GenFiles, type LoadedManifest } from "./load.ts";

export function genDocs({ manifest: m, digest }: LoadedManifest): GenFiles {
  return new Map([[`${m.id}.md`, docsMarkdown(m, digest)]]);
}

function table(head: string[], rows: unknown[][]): string[] {
  return [`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.map(cell).join(" | ")} |`)];
}

function code(v: string | undefined): string {
  return v ? `\`${v.replaceAll("`", "'")}\`` : "";
}

function toolsOf(m: Manifest, op: Manifest["operations"][number]): string {
  if (op.audience !== "agent") return "";
  if (op.dynamic?.mode === "search") {
    const t = dynamicToolNames(m.id, op.id);
    return `${code(t.search)}, ${code(t.call)}`;
  }
  if (op.dynamic?.mode === "list") return `${code(`${m.id}__<entry>`)} per catalog entry`;
  return code(mcpToolName(m.id, op.id));
}

function docsMarkdown(m: Manifest, digest: string): string {
  const out: string[] = [
    "<!-- GENERATED by tb-gen from tealbrick.manifest.json. Do not edit; regenerate with `tb-gen docs`. -->",
    `# ${m.name} (\`${m.id}\`) reference`,
    "",
    m.summary,
    "",
    ...table(
      ["Field", "Value"],
      [
        ["Version", m.version],
        ["SDK major", m.sdkMajor],
        ["Manifest digest", digest],
        ["Publisher", m.publisher.url ? `${m.publisher.name} (${m.publisher.url})` : m.publisher.name],
        ["Source", `${m.source.repo} (${m.source.license})`],
        ["Category", m.discovery.category],
        ["Intents", m.discovery.intents],
      ],
    ),
  ];
  if (m.description) out.push("", m.description);

  const unlockedBy = new Map<string, string>();
  for (const u of m.unlocks ?? []) for (const id of u.provides.operations ?? []) unlockedBy.set(id, u.requires);

  out.push("", "## Operations", "");
  out.push(
    ...table(
      ["Id", "Title", "Audience", "MCP tool", "CRUD", "Effect", "Hold family", "Idempotency", "Receipt", "Scope type"],
      m.operations.map((op) => [code(op.id), op.title, op.audience, toolsOf(m, op), op.crud, op.effect, op.holdFamily, op.idempotency, op.receipt ? "yes" : "no", op.scopeType]),
    ),
  );
  for (const op of m.operations) {
    out.push("", `### \`${op.id}\``, "", op.description);
    if (op.dynamic)
      out.push("", `Dynamic (${op.dynamic.mode} mode): each catalog tool declares its own CRUD and effect within the ceilings crud ${op.dynamic.crudCeiling.join(", ")} / effect ${op.dynamic.effectCeiling}.`);
    const req = unlockedBy.get(op.id);
    if (req) out.push("", `Available only when product \`${req}\` is deployed in the same workspace.`);
    const props = op.input && typeof op.input.properties === "object" && op.input.properties !== null ? Object.keys(op.input.properties) : [];
    if (props.length > 0) {
      const required = new Set(Array.isArray(op.input?.required) ? (op.input.required as string[]) : []);
      out.push("", `Input: ${props.map((p) => (required.has(p) ? `\`${p}\` (required)` : `\`${p}\``)).join(", ")}.`);
    }
  }

  out.push("", "### Standard operations (every SDK app)", "");
  out.push(
    ...table(
      ["Id", "Title", "Audience", "MCP tool", "CRUD", "Effect", "Idempotency"],
      withStandardOps(m)
        .filter((op) => op.standard)
        .map((op) => [code(op.id), op.title, op.audience, op.audience === "agent" ? code(mcpToolName(m.id, op.id)) : "", op.crud, op.effect, op.idempotency]),
    ),
  );

  if ((m.scopes ?? []).length > 0) {
    out.push("", "## Scopes");
    for (const s of m.scopes ?? []) {
      out.push("", `### ${s.label} (\`${s.type}\`)`, "", `Plural: ${s.labelPlural}. Summary template: ${code(s.summaryTemplate)}.`, "");
      out.push(...table(["Access level", "Label", "CRUD"], s.access.map((a) => [code(a.id), a.label, a.crud])));
      out.push(
        "",
        s.defaultGrants.length > 0
          ? `Default grants: ${s.defaultGrants.map((g) => `${g.kind} → \`${g.access}\``).join(", ")}.`
          : "Default grants: none (the owner assigns access in Configure).",
      );
    }
  }

  const envBySetting = new Map<string, string[]>();
  for (const [container, env] of [["app", m.runtime.env ?? []] as const, ...(m.runtime.services ?? []).map((s) => [s.id, s.env ?? []] as const)])
    for (const e of env) if ("setting" in e && e.setting) envBySetting.set(e.setting, [...(envBySetting.get(e.setting) ?? []), `${container}: ${e.name}`]);

  if (m.settings) {
    out.push("", "## Settings");
    for (const step of m.settings.steps) {
      out.push("", `### ${step.title} (\`${step.id}\`)${step.when ? ` — when ${conditionText(step.when)}` : ""}`);
      if (step.help) out.push("", step.help);
      out.push("");
      out.push(
        ...table(
          ["Key", "Type", "Label", "Required", "Default", "Mutable", "When", "Choices", "Env"],
          step.fields.map((f) => [
            code(f.key),
            f.type,
            f.label,
            f.required ? "yes" : "no",
            f.default === undefined ? "" : String(f.default),
            f.mutable === false ? "no" : "yes",
            conditionText(f.when),
            (f.choices ?? []).map((c) => `${c.value}${c.disabled ? " (disabled)" : ""}`),
            envBySetting.get(f.key),
          ]),
        ),
      );
    }
    if ((m.settings.keys ?? []).length > 0) {
      out.push("", "### Keys", "", "Key values never reach Portal or env; the bridge key store (account default) or the app's own UI holds them.", "");
      out.push(
        ...table(
          ["Name", "Label", "Provider", "Required", "Source", "Used by", "When", "Step"],
          (m.settings.keys ?? []).map((k) => [code(k.name), k.label, k.provider, k.required ? "yes" : "no", k.source, k.usedBy, conditionText(k.when), k.step]),
        ),
      );
    }
  }

  if ((m.hooks ?? []).length > 0) {
    out.push("", "## Hooks", "");
    out.push(
      ...table(
        ["Id", "Title", "Phase", "Order", "Products", "Operations", "Effects", "Timeout ms"],
        (m.hooks ?? []).map((h) => [code(h.id), h.title, h.phase, h.order, h.match.products, h.match.operations, h.match.effects, h.timeoutMs ?? 2000]),
      ),
    );
  }

  if ((m.companions ?? []).length > 0 || (m.unlocks ?? []).length > 0) {
    out.push("", "## Companions and unlocks", "");
    for (const c of m.companions ?? []) out.push(`- Companion \`${c.product}\`: ${c.operations.map((o) => `\`${o}\``).join(", ")} (crud ${c.crud.join(", ")}). ${c.purpose}`);
    for (const u of m.unlocks ?? []) {
      const parts = [...(u.provides.operations ?? []).map((o) => `op \`${o}\``), ...(u.provides.skills ?? []).map((s) => `skill \`${s}\``)];
      out.push(`- Unlock \`${u.id}\` (${u.title}): needs \`${u.requires}\`; provides ${parts.join(", ")}.`);
    }
  }

  if ((m.skills ?? []).length > 0) {
    out.push("", "## Skills", "");
    out.push(...table(["Id", "Title", "File", "When"], (m.skills ?? []).map((s) => [code(s.id), s.title, code(s.file), conditionText(s.when)])));
  }
  if ((m.harnessHints ?? []).length > 0) {
    out.push("", "## Harness hints", "");
    for (const h of m.harnessHints ?? []) out.push(`- **${h.harness}**: ${h.instructions.replace(/\s+/g, " ")}`);
  }

  out.push("", "## Backups and export", "");
  out.push(`- Schedule ${code(m.backups.schedule)} (UTC), keep ${m.backups.retain} archives \`tb-backup-<timestamp>.tar.gz\` in \`TB_BACKUP_DIR\`.`);
  for (const f of m.backups.files ?? []) out.push(`- Files: volume \`${f.volume}\`, path \`${f.path}\`.`);
  for (const s of m.runtime.services ?? []) if (s.backup) out.push(`- Service \`${s.id}\`: dump to \`services/${s.id}.${s.backup.extension}\` (${code(s.backup.dump.join(" "))}), restore ${code(s.backup.restore.join(" "))}.`);
  out.push("- Export (`tb.export`): `tb-export-<timestamp>.tar.gz` with `meta.json`, `tables/<name>.jsonl` and `receipts.jsonl`.");

  const r = m.runtime;
  out.push("", "## Runtime", "");
  out.push(
    ...table(
      ["Field", "Value"],
      [
        ["Build", `${r.build.dockerfile} (context ${r.build.context})`],
        ["Port", r.port],
        ["Health path", r.healthPath ?? "/tb/v1/health"],
        ["Resources", `${r.resources.cpu} vCPU, ${r.resources.memoryMb} MB`],
        ["Volumes", r.volumes.map((v) => `${v.id} ${v.mountPath} ${v.sizeGb} GB (${v.purpose})`)],
        ["Env", (r.env ?? []).map(envText)],
      ],
    ),
  );
  if ((r.services ?? []).length > 0) {
    out.push("", "### Services", "");
    out.push(
      ...table(
        ["Id", "Title", "Source", "Port", "Health", "Start order", "When", "Volumes", "Env", "Backup", "Helper"],
        [...(r.services ?? [])]
          .sort((a, b) => a.startOrder - b.startOrder || (a.id < b.id ? -1 : 1))
          .map((s) => [
            code(s.id),
            s.title,
            s.image ? s.image : `build ${s.build?.dockerfile}`,
            s.port,
            s.health.kind === "http" ? `http ${s.health.path}` : "tcp",
            s.startOrder,
            conditionText(s.when),
            (s.volumes ?? []).map((v) => `${v.id} ${v.mountPath} ${v.sizeGb} GB`),
            (s.env ?? []).map(envText),
            s.backup ? "yes" : "no",
            s.helper ? `port ${s.helper.port}` : "",
          ]),
      ),
    );
  }

  if ((m.publicRoutes ?? []).length > 0 || m.ui || (m.artifacts ?? []).length > 0) {
    out.push("", "## Routes, UI and artifacts", "");
    for (const p of m.publicRoutes ?? []) out.push(`- Public route \`/p/${m.id}${p.path}\` (${p.purpose}).`);
    if (m.ui) out.push(`- UI: launch \`/a/${m.id}${m.ui.launchPath}\`${m.ui.configurePath ? `, configure \`/a/${m.id}${m.ui.configurePath}\`` : ""}.`);
    else out.push("- No person UI.");
    for (const a of m.artifacts ?? []) out.push(`- Artifact \`${a.id}\` ${a.version} (sha256 \`${a.sha256}\`).`);
  }
  out.push("");
  return out.join("\n");
}

function envText(e: NonNullable<Manifest["runtime"]["env"]>[number]): string {
  if ("setting" in e && e.setting) return `${e.name} ← setting ${e.setting}`;
  if ("generate" in e && e.generate) return `${e.name} ← generated secret`;
  return `${e.name} = ${e.value}`;
}
