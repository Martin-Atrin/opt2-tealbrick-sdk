// `tb-gen railway`: a self-host Railway template rendered from the manifest (SDK-API §15, C28, C17).
//
// Railway accepts config-as-code only per service (`railway.json`: build + deploy of ONE service; its multi-service
// successor is a TypeScript file, and the template JSON behind `templateDeploy` is not documented). So this emits:
//   railway.json  — Railway config-as-code for the app service (accepted by Railway as is);
//   template.json — a documented neutral description of the whole project (services, start order, one volume per
//                   service, variables in Railway's `${{…}}` reference syntax) to recreate in Railway's template
//                   composer or with its API. Portal deploys never use it: Core's deploy recipe is generated from the
//                   same manifest.
import { statSync } from "node:fs";
import { posix, resolve, sep } from "node:path";
import type { Condition, EnvEntry, Manifest, Service, SettingField } from "@opt2-tealbrick/spec/manifest";
import { GenError, type GenFiles, type LoadedManifest, stableJson } from "./load.ts";

export const TEMPLATE_FORMAT = "tealbrick.railway-template/1";
/** TB_KEK: exactly 32 bytes; 64 lower-case hex chars (SDK-API §13, C35), generated by Railway at first deploy (C17, I3). */
export const KEK_SECRET = '${{secret(64, "0123456789abcdef")}}';
/** `env[].generate: "secret"` (MANIFEST §4). */
export const GENERATED_SECRET = "${{secret(48)}}";
/** SDK-API §13: a `tb-exec` service without a declared volume gets a 1 GB one for `TB_DATA_DIR`. */
const WRAPPER_DATA = { mountPath: "/data", sizeGb: 1 } as const;

export type SettingValue = string | number | boolean;

export interface RailwayOptions {
  /** Setting values to render with (`--set key=value`); unset fields use their manifest default. */
  settings?: Record<string, SettingValue>;
}

interface TemplateService {
  name: string;
  role: "app" | "service";
  manifestId: string;
  source: { image: string } | { repo: string; rootDirectory: string; dockerfilePath: string; configFile?: string };
  startOrder: number;
  internalPort: number;
  healthcheck: { type: "http"; path: string } | { type: "tcp" };
  publicDomain: false;
  resources: { cpu: number; memoryMb: number };
  volume: { mountPath: string; sizeGb: number } | null;
  variables: Record<string, string>;
  inputs: { name: string; required: boolean; description: string }[];
}

/**
 * Build paths are REPO-relative (MANIFEST §3, v0.1.11 (C70)): the emitted `rootDirectory` / `dockerfilePath` are used as
 * written. When the caller named the repo root (`--repo`), the context and every Dockerfile must exist under it.
 */
function checkBuildPaths(lm: LoadedManifest): void {
  if (!lm.repoDirGiven) return;
  const m = lm.manifest;
  const builds = [{ at: "runtime.build", ...m.runtime.build }, ...(m.runtime.services ?? []).flatMap((s) => (s.build ? [{ at: `runtime.services[${s.id}].build`, ...s.build }] : []))];
  for (const b of builds) {
    for (const [field, isDir] of [["context", true], ["dockerfile", false]] as const) {
      const target = resolve(lm.repoDir, b[field]);
      let ok = false;
      try {
        const st = statSync(target);
        ok = isDir ? st.isDirectory() : st.isFile();
      } catch {
        ok = false;
      }
      if (!ok || (target !== lm.repoDir && !target.startsWith(lm.repoDir + sep))) {
        throw new GenError("build_path_missing", `${b.at}.${field} ${b[field]}: no ${isDir ? "directory" : "file"} under the repo root ${lm.repoDir} (build paths are repo-relative)`);
      }
    }
  }
}

export function genRailway(lm: LoadedManifest, opts: RailwayOptions = {}): GenFiles {
  checkBuildPaths(lm);
  const { manifest: m, digest } = lm;
  const settings = resolveSettings(m, opts.settings ?? {});
  const deployed = [...(m.runtime.services ?? [])].filter((s) => matches(s.when, settings)).sort((a, b) => a.startOrder - b.startOrder || (a.id < b.id ? -1 : 1));
  const byId = new Map(deployed.map((s) => [s.id, s]));
  const nameOf = (id: string) => `${m.id}-${id}`;

  const services: TemplateService[] = deployed.map((s) => {
    const wrapper = s.build !== undefined;
    const volume = mergedVolume(s.volumes ?? [], wrapper ? WRAPPER_DATA : null);
    const variables = renderEnv(s.env ?? [], settings, byId, nameOf);
    variables.PORT ??= String(s.port);
    if (wrapper) {
      variables.TB_KEK = KEK_SECRET;
      variables.TB_SERVICE = s.id;
      if (volume) variables.TB_DATA_DIR = volume.mountPath;
    }
    return {
      name: nameOf(s.id),
      role: "service",
      manifestId: s.id,
      source: s.build !== undefined ? { repo: m.source.repo, ...buildSource(s.build) } : { image: s.image as string },
      startOrder: s.startOrder,
      internalPort: s.port,
      healthcheck: s.health.kind === "http" ? { type: "http", path: s.health.path } : { type: "tcp" },
      publicDomain: false,
      resources: { ...s.resources },
      volume,
      variables,
      inputs: wrapper ? bridgeInputs(false) : [],
    };
  });

  const appVolume = mergedVolume(m.runtime.volumes, null);
  if (!appVolume) throw new GenError("manifest_invalid", "runtime.volumes has no data volume");
  const appVars = renderEnv(m.runtime.env ?? [], settings, byId, nameOf);
  appVars.PORT ??= String(m.runtime.port);
  appVars.TB_KEK = KEK_SECRET;
  appVars.TB_DATA_DIR = appVolume.mountPath;
  appVars.TB_BACKUP_DIR = posix.join(appVolume.mountPath, "backup");
  const healthPath = m.runtime.healthPath ?? "/tb/v1/health";
  services.push({
    name: m.id,
    role: "app",
    manifestId: "app",
    source: { repo: m.source.repo, ...buildSource(m.runtime.build), configFile: "railway.json" },
    startOrder: (deployed.at(-1)?.startOrder ?? -1) + 1,
    internalPort: m.runtime.port,
    healthcheck: { type: "http", path: healthPath },
    publicDomain: false,
    resources: { ...m.runtime.resources },
    volume: appVolume,
    variables: appVars,
    inputs: [...bridgeInputs(true), ...unsetSettingInputs(m, settings)],
  });

  const dataVolumes = m.runtime.volumes.filter((v) => v.purpose === "data");
  const notes = [
    "Neutral description, not a Railway file format: recreate these services in Railway's template composer or API. railway.json is Railway config-as-code for the app service.",
    "Apps are private: no service gets a public domain. Agents reach the app only through a Teal Brick bridge in the same Railway project (the bridge is the only public address); set TB_BRIDGE_URL, TB_ENROL_CODE, TB_PORTAL_KEYS and TB_INSTANCE_ID when connecting one.",
    "Without a bridge, TB_STANDALONE=1 runs the app alone for persons only (no agent access).",
    `One volume per service (C28): the app's backup volume is merged into its data volume at ${appVolume.mountPath}; TB_BACKUP_DIR=${appVars.TB_BACKUP_DIR}.`,
    "TB_KEK is generated by Railway at first deploy and never leaves the project. Keys (settings.keys) are never env: the bridge key store or the app UI holds them.",
    "Services start in ascending startOrder; ties start in parallel; the app starts last. Private URLs use ${{<service>.RAILWAY_PRIVATE_DOMAIN}}.",
  ];
  // SPEC-GAP: MANIFEST allows several app data volumes, Railway mounts one volume per service (C28 names only "the
  // data volume"). The first data volume is mounted with the summed size; the others are listed here.
  if (dataVolumes.length > 1)
    notes.push(`Extra app data volumes are not mountable on Railway and are merged into ${appVolume.mountPath}: ${dataVolumes.slice(1).map((v) => `${v.id} (${v.mountPath})`).join(", ")}.`);
  const skipped = (m.runtime.services ?? []).filter((s) => !byId.has(s.id)).map((s) => s.id);
  if (skipped.length > 0) notes.push(`Not deployed with these settings (service when): ${skipped.join(", ")}.`);

  const template = {
    $comment: "GENERATED by tb-gen from tealbrick.manifest.json. Do not edit; regenerate with `tb-gen railway`.",
    format: TEMPLATE_FORMAT,
    product: m.id,
    name: m.name,
    version: m.version,
    manifestDigest: digest,
    settings,
    notes,
    services,
  };
  const configAsCode = {
    $schema: "https://railway.com/railway.schema.json",
    build: { builder: "DOCKERFILE", dockerfilePath: buildSource(m.runtime.build).dockerfilePath },
    deploy: { healthcheckPath: healthPath, restartPolicyType: "ON_FAILURE", restartPolicyMaxRetries: 10 },
  };
  return new Map([
    ["railway.json", stableJson(configAsCode)],
    ["template.json", stableJson(template)],
  ]);
}

function buildSource(b: { context: string; dockerfile: string }): { rootDirectory: string; dockerfilePath: string } {
  const root = posix.normalize(b.context);
  return { rootDirectory: root, dockerfilePath: root === "." ? posix.normalize(b.dockerfile) : posix.relative(root, posix.normalize(b.dockerfile)) };
}

/** The container's first data volume carries every declared volume's size (one volume per service, C28). */
function mergedVolume(volumes: readonly { mountPath: string; sizeGb: number; purpose: string }[], fallback: { mountPath: string; sizeGb: number } | null) {
  const data = volumes.find((v) => v.purpose === "data");
  if (!data) return fallback ? { ...fallback } : null;
  return { mountPath: data.mountPath, sizeGb: volumes.reduce((n, v) => n + v.sizeGb, 0) };
}

function renderEnv(env: readonly EnvEntry[], settings: Record<string, SettingValue>, deployed: Map<string, Service>, nameOf: (id: string) => string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const e of env) {
    if (e.generate !== undefined) out[e.name] = GENERATED_SECRET;
    else if (e.setting !== undefined) {
      const v = settings[e.setting];
      if (v !== undefined) out[e.name] = String(v);
    } else {
      const value = renderTemplate(e.value as string, deployed, nameOf);
      if (value !== null) out[e.name] = value;
    }
  }
  return out;
}

/** `{{services.<id>.url|host|port|env.<NAME>}}` → Railway references; null when the service is not deployed (MANIFEST §4). */
function renderTemplate(value: string, deployed: Map<string, Service>, nameOf: (id: string) => string): string | null {
  let missing = false;
  const out = value.replace(/\{\{services\.([a-z0-9-]+)\.(url|host|port|env\.([A-Z][A-Z0-9_]*))\}\}/g, (_w, id: string, kind: string, envName?: string) => {
    const s = deployed.get(id);
    if (!s) {
      missing = true;
      return "";
    }
    const host = `\${{${nameOf(id)}.RAILWAY_PRIVATE_DOMAIN}}`;
    if (kind === "url") return `http://${host}:${s.port}`;
    if (kind === "host") return host;
    if (kind === "port") return String(s.port);
    return `\${{${nameOf(id)}.${envName}}}`;
  });
  return missing ? null : out;
}

function bridgeInputs(app: boolean): TemplateService["inputs"] {
  const list = [
    { name: "TB_BRIDGE_URL", required: false, description: "Bridge internal base URL (private network); set when connecting a bridge." },
    { name: "TB_ENROL_CODE", required: false, description: "One-time claim code issued for this instance." },
    { name: "TB_PORTAL_KEYS", required: false, description: "Portal public JWKS JSON (public values only)." },
    { name: "TB_INSTANCE_ID", required: false, description: "Own ins_ id; absent in app-alone mode." },
  ];
  if (app) list.push({ name: "TB_STANDALONE", required: false, description: "1 = app-alone mode: persons only, no agents (no bridge)." });
  return list;
}

function unsetSettingInputs(m: Manifest, settings: Record<string, SettingValue>): TemplateService["inputs"] {
  const fields = new Map((m.settings?.steps ?? []).flatMap((s) => s.fields).map((f) => [f.key, f]));
  return (m.runtime.env ?? [])
    .filter((e) => e.setting !== undefined && settings[e.setting] === undefined)
    .map((e) => {
      const f = fields.get(e.setting as string) as SettingField;
      return { name: e.name, required: f.required === true, description: `Setting ${f.key} (${f.type}): ${f.label}` };
    });
}

function matches(when: Condition | undefined, settings: Record<string, SettingValue>): boolean {
  if (!when) return true;
  return Object.entries(when).every(([k, want]) => {
    const v = settings[k];
    return v !== undefined && (Array.isArray(want) ? want.includes(v) : want === v);
  });
}

/** Setting values used for rendering: `overrides` (checked against the field's type and choices) over manifest defaults. */
export function resolveSettings(m: Manifest, overrides: Record<string, SettingValue>): Record<string, SettingValue> {
  const fields = (m.settings?.steps ?? []).flatMap((s) => s.fields);
  const out: Record<string, SettingValue> = {};
  for (const f of fields) if (f.default !== undefined) out[f.key] = f.default;
  for (const [key, raw] of Object.entries(overrides)) {
    const f = fields.find((x) => x.key === key);
    if (!f) throw new GenError("setting_unknown", `no setting field ${key}`);
    out[key] = coerce(f, raw);
  }
  return out;
}

function coerce(f: SettingField, raw: SettingValue): SettingValue {
  const bad = () => new GenError("setting_invalid", `setting ${f.key} (${f.type}): invalid value ${JSON.stringify(raw)}`);
  switch (f.type) {
    case "boolean":
      if (raw === true || raw === "true") return true;
      if (raw === false || raw === "false") return false;
      throw bad();
    case "integer":
    case "number": {
      const n = typeof raw === "number" ? raw : Number(raw);
      if (raw === "" || !Number.isFinite(n) || (f.type === "integer" && !Number.isInteger(n))) throw bad();
      return n;
    }
    case "enum": {
      const c = f.choices?.find((x) => x.value === String(raw));
      if (!c || c.disabled) throw bad();
      return c.value;
    }
    default:
      return String(raw);
  }
}
