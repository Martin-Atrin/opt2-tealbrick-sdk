// Generates src/generated/sdk-exports.ts from the runtime declarations of `@opt2-tealbrick/spec/sdk` (types/sdk.ts:
// `export declare function|class|const`) — CONFORMANCE A11. `--check` exits 1 when the committed file is stale (CI).
// Package attribution follows the declaration order of types/sdk.ts: §A manifest primitives come before `TbError`,
// §B server exports before `TbProviderProps`, §C client exports after it.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const dts = fileURLToPath(import.meta.resolve("@opt2-tealbrick/spec/sdk")).replace(/\.js$/, ".d.ts");
const text = readFileSync(dts, "utf8");
const serverStart = text.indexOf("export declare class TbError");
const clientStart = text.indexOf("TbProviderProps");
if (serverStart < 0 || clientStart < 0) throw new Error("sdk.d.ts layout changed: TbError / TbProviderProps markers not found");

const seen = new Map<string, { name: string; kind: string; pkg: string }>();
for (const m of text.matchAll(/^export declare (function|class|const) ([A-Za-z0-9_]+)/gm)) {
  const at = m.index ?? 0;
  const pkg = at < serverStart ? "@opt2-tealbrick/manifest" : at < clientStart ? "@opt2-tealbrick/miniapp-sdk" : "@opt2-tealbrick/miniapp-sdk/client";
  if (!seen.has(m[2])) seen.set(m[2], { name: m[2], kind: m[1], pkg });
}
const rows = [...seen.values()].sort((a, b) => a.pkg.localeCompare(b.pkg) || a.name.localeCompare(b.name));
const out = `// GENERATED by scripts/gen-sdk-exports.ts from @opt2-tealbrick/spec/sdk (types/sdk.ts) — do not edit.
// CONFORMANCE A11: every entry must map to >= 1 check id in src/sdk-coverage.ts.

export interface SdkExport {
  name: string;
  kind: "function" | "class" | "const";
  pkg: "@opt2-tealbrick/manifest" | "@opt2-tealbrick/miniapp-sdk" | "@opt2-tealbrick/miniapp-sdk/client";
}

export const SDK_EXPORTS: readonly SdkExport[] = [
${rows.map((r) => `  { name: "${r.name}", kind: "${r.kind}", pkg: "${r.pkg}" },`).join("\n")}
];
`;
const target = fileURLToPath(new URL("../src/generated/sdk-exports.ts", import.meta.url));
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    current = "";
  }
  if (current !== out) {
    console.error("src/generated/sdk-exports.ts is stale: run `node scripts/gen-sdk-exports.ts`");
    process.exit(1);
  }
  console.log(`sdk-exports up to date (${rows.length} exports)`);
} else {
  writeFileSync(target, out);
  console.log(`wrote ${rows.length} exports`);
}
